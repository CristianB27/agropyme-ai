def error_de_escritura(texto: str, rng: random.Random) -> str:
    """Aplica un error típico de teclado o de ortografía."""
    opcion = rng.random()
    if opcion < 0.35:
        candidatos = [s for s in SUSTITUCIONES if s[0] in texto]
        if candidatos:
            viejo, nuevo = rng.choice(candidatos)
            return texto.replace(viejo, nuevo, 1)
    letras = [i for i, c in enumerate(texto) if c.isalpha()]
    if len(letras) < 4:
        return texto
    i = rng.choice(letras)
    if opcion < 0.55:
        return texto[:i] + texto[i + 1:]
    if opcion < 0.75:
        return texto[:i] + texto[i] + texto[i:]
    if opcion < 0.9 and i + 1 < len(texto) and texto[i + 1].isalpha():
        return texto[:i] + texto[i + 1] + texto[i] + texto[i + 2:]
    vecinas = TECLAS_VECINAS.get(texto[i])
    if vecinas:
        return texto[:i] + rng.choice(vecinas) + texto[i + 1:]
    return texto


def construir(semilla: int = 13, variantes_por_nucleo: int = 14) -> list[tuple[str, str]]:
    rng = random.Random(semilla)
    filas: list[tuple[str, str]] = []
    for intencion, nucleos in NUCLEOS.items():
        for nucleo in nucleos:
            filas.append((intencion, nucleo))
            for _ in range(variantes_por_nucleo):
                texto = rng.choice(PREFIJOS) + nucleo
                if intencion not in SIN_SUFIJO:
                    texto += rng.choice(SUFIJOS)
                if rng.random() < 0.3:
                    texto = "¿" + texto + "?"
                elif rng.random() < 0.2:
                    texto += "?"
                if rng.random() < 0.35:
                    texto = error_de_escritura(texto, rng)
                if rng.random() < 0.1:
                    texto = error_de_escritura(texto, rng)
                filas.append((intencion, texto))
    for intencion, texto in FILAS_SUELTAS:
        for _ in range(4):
            filas.append((intencion, rng.choice(PREFIJOS) + texto))
    # Sin duplicados exactos, en orden estable.
    vistos: set[tuple[str, str]] = set()
    unicas = []
    for fila in filas:
        if fila not in vistos:
            vistos.add(fila)
            unicas.append(fila)
    return unicas
